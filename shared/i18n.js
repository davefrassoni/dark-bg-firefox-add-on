  function resolveLanguage(selectedLanguage, browserLanguages) {
    if (SUPPORTED_LANGUAGES.includes(selectedLanguage)) {
      return selectedLanguage;
    }
    for (const language of browserLanguages || []) {
      const normalized = String(language).replace("-", "_");
      if (SUPPORTED_LANGUAGES.includes(normalized)) {
        return normalized;
      }
      const base = normalized.split("_")[0];
      if (base === "pt") {
        return "pt_BR";
      }
      if (base === "zh") {
        return "zh_CN";
      }
      if (SUPPORTED_LANGUAGES.includes(base)) {
        return base;
      }
    }
    return "en";
  }

  function translator(language) {
    const strings = TRANSLATIONS[language] || TRANSLATIONS.en;
    return (key) => strings[key] || TRANSLATIONS.en[key] || key;
  }

  // Applies data-i18n (text), data-i18n-placeholder and data-i18n-title.
  function translateDocument(document, language) {
    const t = translator(language);
    document.documentElement.lang = language.replace("_", "-");
    document.documentElement.dir = RTL_LANGUAGES.includes(language) ? "rtl" : "ltr";
    document.querySelectorAll("[data-i18n]").forEach((element) => {
      element.textContent = t(element.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
      element.placeholder = t(element.dataset.i18nPlaceholder);
    });
    document.querySelectorAll("[data-i18n-title]").forEach((element) => {
      element.title = t(element.dataset.i18nTitle);
    });
    return t;
  }

  return {
    SUPPORTED_LANGUAGES,
    RTL_LANGUAGES,
    MANIFEST_KEYS,
    TRANSLATIONS,
    resolveLanguage,
    translator,
    translateDocument
  };
